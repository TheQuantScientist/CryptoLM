# 4.  PARSER — tìm số trong bất kỳ định dạng nào
# ══════════════════════════════════════════════════════════════
def extract_numbers(text: str) -> list:
    """
    Tìm TẤT CẢ số trong output của LLM, bất kể định dạng:
    - Phân cách bằng , hoặc ; hoặc : hoặc - hoặc | hoặc khoảng trắng
    - Có bullet points (*, -, +, •)
    - Có số thứ tự (1. 2. 3.)
    - Có text giải thích xen kẽ
    - Có số khoa học (1.5e-3)
    - Có định dạng tiền tệ ($1,234.56)
    Trả về list[float], rỗng nếu không tìm thấy.
    """
    if not text:
        return []

    clean = str(text)

    # Xóa code fences
    clean = re.sub(r'```[\w\s]*```', ' ', clean, flags=re.DOTALL)
    clean = re.sub(r'```[\w]*', ' ', clean)

    # Xóa ký hiệu tiền tệ ($ € £ ¥) để không nhầm với số âm
    clean = re.sub(r'[$€£¥₫]', ' ', clean)

    # Chuẩn hóa "1.5 x 10^3" hoặc "1.5×10^3" → số thực
    clean = re.sub(
        r'(\d+\.?\d*)\s*[xX×]\s*10\s*\^?\s*([-+]?\d+)',
        lambda m: str(float(m.group(1)) * 10 ** int(m.group(2))),
        clean
    )

    # Xóa bullet points và số thứ tự để không nhầm
    # (nhưng giữ số thực sau chúng)
    clean = re.sub(r'(?:^|\n)\s*[\*\-\+•]\s*', ' ', clean)
    clean = re.sub(r'(?:^|\n)\s*\d+[\.\)]\s*', ' ', clean)

    # Thay tất cả dấu phân cách lạ (;, :, |, /) thành khoảng trắng
    # Không xóa dấu . và , vì chúng là phần của số
    clean = re.sub(r'[;:|/\\]', ' ', clean)

    # Tìm tất cả số: nguyên, thực, khoa học, âm
    # Pattern này bắt: 123, 123.45, .45, 1.5e-3, -123.45
    pattern = r'[-+]?(?:\d{1,15}(?:\.\d+)?|\.\d+)(?:[eE][-+]?\d+)?'
    matches = re.findall(pattern, clean)

    result = []
    for m in matches:
        try:
            val = float(m)
            # Lọc bỏ số vô lý: âm (giá crypto không âm), quá lớn, NaN, Inf
            if val > 0 and not np.isnan(val) and not np.isinf(val) and val < 1e12:
                result.append(val)
        except Exception:
            pass

    return result


def parse_llm_output(text: str, horizon: int, past_data: list = None):
    """
    Từ output LLM → lấy đúng `horizon` số hợp lệ.

    Bước 1: extract tất cả số từ text
    Bước 2: lọc outlier dựa trên range của past_data
            → loại số mà parser vô tình bắt từ số thứ tự, timestamp...
            → ví dụ: XLMUSDT actual~0.2, model trả "0.201" nhưng
              parser đọc thành "201.0" vì dòng "1. 0.201" → loại
    Bước 3: nếu >= horizon → lấy horizon số cuối
    Bước 4: nếu < horizon → None → retry

    Trả về list[float] hoặc None.
    """
    nums = extract_numbers(text)

    # ── Lọc outlier theo range past_data ────────────────────────────
    if past_data and len(past_data) > 0:
        arr   = np.array(past_data, dtype=float)
        p_min = arr.min()
        p_max = arr.max()

        # Biên dưới: cho phép giảm tối đa 50% so với min
        lo = p_min * 0.5

        # Biên trên: tùy scale giá
        # - Coin nhỏ (< 1$): chặt hơn, tối đa 5x → tránh nhầm 0.201 → 201
        # - Coin vừa (1–100$): tối đa 8x
        # - Coin lớn (> 100$): tối đa 10x (BTC có thể tăng mạnh)
        if p_max < 1.0:
            hi = p_max * 5.0
        elif p_max < 100.0:
            hi = p_max * 8.0
        else:
            hi = p_max * 10.0

        nums = [x for x in nums if lo <= x <= hi]

    if len(nums) >= horizon:
        # Lấy horizon số cuối — model thường viết giải thích trước,
        # số dự đoán thật nằm ở cuối response
        return nums[-horizon:]

    # Thiếu ít (≤ 3 số) sau khi lọc outlier → fill bằng số cuối (vẫn là số của LLM)
    # Ví dụ: model trả 29 số đúng + 1 số sai bị lọc → fill 1 → không cần retry
    if len(nums) >= horizon - 3 and len(nums) > 0:
        shortage = horizon - len(nums)
        return nums + [nums[-1]] * shortage

    # Không đủ số → None → trigger retry
    return None


